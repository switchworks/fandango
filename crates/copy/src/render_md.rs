//!
//! **共有ヘッド → 英語全文 → `<hr>` → 日本語全文。** 導線 (`Get it`) と 12 本の表は
//! どちらの言語節にも属さない共有ブロックとして、言語分割より**上**に置く。
//! §5 の「表は 1 回だけ出す」は維持しており、変わったのは位置だけ。上へ出したことで
//! 英日混在がそのブロックの体裁として成立する (分割の内側にあると「英語節に日本語が
//! 混ざっている」ように見えていた)。
//! 動作環境・インストール・ライセンス・Disclaimer は英語 1 回だけ。

use crate::Copy;

/// GitHub は `style` 属性を落とすので、日本語行は `<sub>` で一段落とす。
fn stacked(en: &str, ja: &str) -> String {
    format!("{en}<br><sub>{ja}</sub>")
}

/// 手編集を止めるための先頭マーカー (`plans/copy_source_v01.md` 不変条件 2)。
pub const MARKER: &str =
    "<!-- generated by `cargo run -p fandango-copy --bin copygen -- readme`. Edit copy.toml / copy/*.md, not this file. -->";

pub fn render(c: &Copy) -> String {
    let mut s = String::new();
    s.push_str(MARKER);
    s.push_str("\n\n");

    s.push_str(&format!("# {} by {}\n\n", c.meta.name, c.meta.author));
    // タグラインだけは共有ヘッドで英日を並べる。1 行ずつなので軽く、最上部で二言語で
    // あることが伝わる (日本語節まで下がらないと日本語が出てこない状態を避ける)。
    // ja を `<sub>` に落とさないのは意図的で、見出し相当の重みを持つため。
    s.push_str(&format!("> **{}**<br>**{}**\n\n", c.tagline.en, c.tagline.ja));
    s.push_str(&format!("{}\n\n", c.prose.lead.en));
    s.push_str("---\n\n");
    s.push_str(&format!(
        "![{} — 12 plugins](docs/images/tile.png)\n\n",
        c.meta.name
    ));
    s.push_str("---\n\n");

    // --- 共有ブロック (言語分割より上)。読者が最初に見たいのは設計思想ではなく
    // 「どこで手に入るか」と「何が入っているか」なので、その 2 つを先に出す。
    s.push_str(&format!(
        "## {} / {}\n\n",
        c.headings.get.en, c.headings.get.ja
    ));
    s.push_str(&format!("{}\n\n", c.prose.get.en));
    s.push_str(&format!("{}\n\n", c.prose.get.ja));

    s.push_str("---\n\n");
    s.push_str(&plugins_section(c));

    // --- ここから英語全文 ---
    s.push_str("---\n\n");
    s.push_str(&format!("## {}\n\n", c.headings.what_is.en));
    s.push_str(&format!("{}\n\n", c.prose.what_is.en));
    s.push_str(&format!("{}\n\n", c.prose.promises.en));
    s.push_str(&format!("{}\n\n", c.prose.tradeoff.en));

    s.push_str(&format!("## {}\n\n", c.headings.requirements.en));
    s.push_str(&format!("{}\n\n", c.prose.requirements.en));
    s.push_str(&format!("## {}\n\n", c.headings.install.en));
    s.push_str(&format!("{}\n\n", c.prose.install.en));
    s.push_str(&format!("## {}\n\n", c.headings.license.en));
    s.push_str(&format!("{}\n\n", c.prose.license.en));

    s.push_str(&format!("## {}

", c.headings.fb2k.en));
    s.push_str(&format!("{}

", c.prose.fb2k.en));
    s.push_str(&format!("## {}\n\n", c.headings.more.en));
    s.push_str(&format!("{}\n\n", c.prose.more.en));

    // ここから日本語全文。畳まない (§5)。タグラインと導線 (`Get it`) は共有ヘッドへ
    // 移したので、ここでは繰り返さない。
    s.push_str("---\n\n");
    s.push_str(&format!("{}\n\n", c.prose.lead.ja));
    s.push_str(&format!("## {}\n\n", c.headings.what_is.ja));
    s.push_str(&format!("{}\n\n", c.prose.what_is.ja));
    s.push_str(&format!("{}\n\n", c.prose.promises.ja));
    s.push_str(&format!("{}\n\n", c.prose.tradeoff.ja));
    s.push_str(&format!("## {}\n\n", c.headings.more.ja));
    s.push_str(&format!("{}\n\n", c.prose.more.ja));

    s.push_str("---\n\n");
    s.push_str(&format!("## {}\n\n", c.headings.disclaimer.en));
    s.push_str(&format!("{}\n", c.prose.disclaimer.en));

    s
}

/// starters ブロックと 12 本の表。英語ブロックにも日本語ブロックにも属さない共有の
/// 節として、言語分割より**上**に 1 回だけ置く。読者が最初に見たいのは設計思想では
/// なく収録内容なので、`What this is` より前に出す。
fn plugins_section(c: &Copy) -> String {
    let mut s = String::new();
    s.push_str(&format!(
        "## {} / {}\n\n",
        c.headings.plugins.en, c.headings.plugins.ja
    ));
    s.push_str(&format!(
        "**{}**<br><sub>{}</sub>\n\n",
        c.starters.heading.en, c.starters.heading.ja
    ));
    for id in &c.starters.order {
        let note = &c.starters.note[id];
        s.push_str(&format!(
            "- **`:{id}`** — {}\n",
            stacked(&note.en, &note.ja)
        ));
    }
    s.push('\n');

    s.push_str(&format!(
        "**{}**<br><sub>{}</sub>

",
        c.headings.plugins_all.en, c.headings.plugins_all.ja
    ));
    s.push_str("| Plugin | Type | |\n|---|---|---|\n");
    for p in &c.plugins {
        s.push_str(&format!(
            "| **`:{}`** | {} | {} |\n",
            p.id,
            stacked(&p.kind.en, &p.kind.ja),
            stacked(&p.line.en, &p.line.ja),
        ));
    }
    s.push('\n');
    s
}
